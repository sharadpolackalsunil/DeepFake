from scipy.stats import betabinom, binom

ROOT = Path(__file__).resolve().parents[1]
RT = ROOT / "results" / "tables"
OUT = ROOT / "paper" / "tables"
FIG = ROOT / "paper" / "figures"
OUT.mkdir(parents=True, exist_ok=True)

ARCH_ORDER = ["gend_official", "gend_ours", "smsdt_s", "smsdt_st", "smsdt_full"]
ARCH_TEX = {
    "gend_official": r"GenD (official)$^\dagger$",
    "gend_ours": r"GenD-style (ours)",
    "smsdt_s": r"S-MSDT-S",
    "smsdt_st": r"S-MSDT-ST",
    "smsdt_full": r"S-MSDT-Full",
}
PARAMS = {"gend_official": "0.10M", "gend_ours": "0.10M", "smsdt_s": "0.78M",
          "smsdt_st": "8.47M", "smsdt_full": "9.10M"}
T_FRAMES = {"gend_official": 1, "gend_ours": 1, "smsdt_s": 1, "smsdt_st": 8, "smsdt_full": 8}
DS_TEX = {"ffpp": "FF++", "celebdf": "Celeb-DF", "dfd": "DFD", "fakeavceleb": "FakeAVCeleb"}


def arch_of(model: str) -> str:
    for a in sorted(ARCH_ORDER, key=len, reverse=True):
        if model.startswith(a):
            return a
    raise ValueError(model)


def f(x, d=3):
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def pm(mean, sd, d=3, n=1):
    if n <= 1 or sd is None or (isinstance(sd, float) and math.isnan(sd)):
        return f(mean, d)
    return f"{mean:.{d}f}$\\pm${sd:.{d}f}"


def write(name: str, body: str) -> None:
    (OUT / f"{name}.tex").write_text("% AUTO-GENERATED by tools/paper_tables.py -- do not edit by hand\n" + body)


# ---------------------------------------------------------------- Table: ranking vs budget
def table_ranking_vs_budget() -> dict:
    em = pd.read_csv(RT / "experiment_matrix.csv")
    em["arch"] = em.Model.map(arch_of)
    fc = pd.read_csv(RT / "fpr_control.csv")
    sq = fc[(fc.policy == "source_quantile") & (fc.alpha == 0.05)]
    stats = {}
    rows = []
    for a in ARCH_ORDER:
        e = em[em.arch == a]
        n = len(e)
        cells = []
        for ds in ["celebdf", "dfd", "fakeavceleb"]:
            cells.append(pm(e[f"{ds}_auc"].mean(), e[f"{ds}_auc"].std(), 3, n))
        for ds in ["celebdf", "dfd", "fakeavceleb"]:
            s = sq[(sq.model == a) & (sq.dataset == ds)].fpr
            stats[(a, ds)] = (s.mean(), s.min(), s.max())
            v = pm(s.mean(), s.std(), 3, len(s))
            if s.mean() > 0.10:
                v = r"\textbf{" + v + "}"
            cells.append(v)
        rows.append(f"{ARCH_TEX[a]} & {n} & " + " & ".join(cells) + r" \\")
    body = r"""\begin{table}[t]
\centering
\small
\setlength{\tabcolsep}{4pt}
\caption{Ranking quality does not predict whether the false-alarm budget is kept. Left: video AUC. Right: false-positive rate on authentic target videos when the alert threshold is the $95$th percentile of FF++ validation reals (nominal budget $\alpha=0.05$). Mean$\pm$sd over training seeds; bold marks rates above $2\alpha$. $^\dagger$Published checkpoint, single run.}
\label{tab:ranking_vs_budget}
\resizebox{\linewidth}{!}{%
\begin{tabular}{lc ccc ccc}
\toprule
 & & \multicolumn{3}{c}{Video AUC $\uparrow$} & \multicolumn{3}{c}{FPR at source threshold ($\alpha=0.05$)} \\
\cmidrule(lr){3-5}\cmidrule(lr){6-8}
Detector & Seeds & Celeb-DF & DFD & FakeAVCeleb & Celeb-DF & DFD & FakeAVCeleb \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}}
\end{table}
"""
    write("ranking_vs_budget", body)
    return stats


