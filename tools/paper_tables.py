def table_real_shot() -> dict:
    d = pd.read_csv(RT / "real_shot_curve_confirm_fakeavceleb.csv")
    x = d[(d.alpha == 0.05) & (d.n_real_identities == 20)]
    o = d[(d.alpha == 0.05) & (d.policy == "oracle")].groupby(["model", "seed"]).mean_tpr.first()
    src = d[(d.alpha == 0.05) & (d.policy == "source_quantile")].groupby(["model", "seed"]).mean_fpr.first()
    res = []
    for (m, s), gr in x.groupby(["model", "seed"]):
        c = gr[gr.policy == "conformal"].iloc[0]
        nq = gr[gr.policy == "naive_quantile"].iloc[0]
        res.append(dict(model=m, seed=s, conf_fpr=c.mean_fpr, conf_p2=c.p_fpr_gt_2alpha, conf_tpr=c.mean_tpr,
                        oracle=o.loc[(m, s)], naive_fpr=nq.mean_fpr, naive_p2=nq.p_fpr_gt_2alpha,
                        src_fpr=src.loc[(m, s)]))
    r = pd.DataFrame(res)
    r["ret"] = r.conf_tpr / r.oracle
    r.to_csv(OUT / "_real_shot_n20_per_run.csv", index=False)
    rows = []
