"""Generate every number-bearing table and the H8 figures of the TMLR manuscript
directly from committed results in results/tables/.

Usage:  python tools/paper_tables.py            (writes paper/tables/*.tex, paper/figures/fig6*, fig7*)

No numbers in paper/tables/ are typed by hand; edit this script and re-run instead.
"""
from __future__ import annotations

import json
import math
