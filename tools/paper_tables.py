# ---------------------------------------------------------------- planner
def table_planner() -> dict:
    def p(n, alpha, m):
        k = math.ceil((n + 1) * (1 - alpha))
        if k > n:
            return None
        return 1 - betabinom.cdf(math.floor(2 * alpha * m), m, n + 1 - k, k)

    def e(n, alpha):
        k = math.ceil((n + 1) * (1 - alpha))
        return (n + 1 - k) / (n + 1)
    ms = [100, 250, 500, 1000]
    rows = []
    for alpha, ns in [(0.05, [19, 20, 30, 39, 59, 79, 99]), (0.10, [9, 19, 29, 49])]:
        for n in ns:
            cells = [f(p(n, alpha, m)) for m in ms]
            rows.append(f"{alpha:.2f} & {n} & {math.ceil((n+1)*(1-alpha))} & {f(e(n, alpha),4)} & " + " & ".join(cells) + r" \\")
        rows.append(r"\midrule")
    rows = rows[:-1]
    write("planner", r"""\begin{table}[t]
\centering
\small
\caption{Sample-size planner computed from Proposition~\ref{prop:bb}: expected FPR of the conformal threshold and the probability that the FPR measured on $m$ held-out authentic identities exceeds $2\alpha$. Sweet spots ($n=j/\alpha-1$) give an expected FPR of exactly $\alpha$; between them the rule is conservative (e.g.\ $n=30$). The probability also depends on $m$: small audits are noisier.}
\label{tab:planner}
\begin{tabular}{cc c c cccc}
\toprule
 & & & & \multicolumn{4}{c}{$P(\mathrm{FPR}_{\mathrm{eval}}>2\alpha)$ for held-out size $m$} \\
\cmidrule(lr){5-8}
$\alpha$ & $n$ & $k$ & $\mathbb{E}[\mathrm{FPR}]$ & $m=100$ & $m=250$ & $m=500$ & $m=1000$ \\
\midrule
""" + "\n".join(rows) + r"""
\bottomrule
\end{tabular}
\end{table}
""")
    return {"p": p}


